function initialLanguage(): Language {
  try {
    const saved = window.localStorage.getItem('asset-studio-language')
    if (saved === 'en' || saved === 'id') return saved
  } catch { /* storage may be unavailable */ }
  return window.navigator.language.toLowerCase().startsWith('id') ? 'id' : 'en'
}

type LanguageContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: string, values?: Record<string, string | number>) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage)
  useEffect(() => {
    document.documentElement.lang = language
    try { window.localStorage.setItem('asset-studio-language', language) } catch { /* storage may be unavailable */ }
  }, [language])
  const t = (key: string, values?: Record<string, string | number>) => {
    const template = language === 'id' ? indonesian[key] ?? key : key
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? `{${name}}`))
  }
  return <LanguageContext.Provider value={{ language, setLanguage, t }}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('LanguageProvider is missing')
  return context
}
