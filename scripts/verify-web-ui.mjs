import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createHash } from 'node:crypto';
import { PNG } from 'pngjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const url = process.env.WEB_URL || 'http://127.0.0.1:5173';
const screenshots = join(root, 'apps/web/.generated');
mkdirSync(screenshots,{recursive:true});
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const file = (key,format,bytes,more = {}) => ({key,url:`/published/${hash(Buffer.from(key))}.${format}`,format,bytes:bytes.length,sha256:hash(bytes),...more});
const png = new PNG({width:48,height:32});
for (let i = 0; i < png.data.length; i += 4) png.data.set([98,107,229,255],i);
const picture = PNG.sync.write(png);
const detail = new PNG({width:32,height:48});
for (let i = 0; i < detail.data.length; i += 4) detail.data.set([249,142,76,255],i);
const detailPicture = PNG.sync.write(detail);
const svg = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 32"><circle cx="24" cy="16" r="12" fill="#626be5"/></svg>');
const hero = file('hero','png',picture,{dimensions:{width:48,height:32},caption:'Final render'});
const wireframe = file('wireframe','png',detailPicture,{dimensions:{width:32,height:48},caption:'Wireframe study'});
const missingPreview = file('missing','png',picture,{caption:'Unavailable image'});
const pngDownload = file('png-download','png',picture,{label:'PNG export'});
const svgDownload = file('svg-download','svg',svg,{label:'SVG export'});
const fixtureCatalog = {schemaVersion:1,assets:[],logicalAssets:[],showcases:[
  {id:'cv/icon',projectId:'cv',slug:'icon',title:'CV Icon',description:'A considered identity for a personal site',category:'branding',publication:'downloadable',tags:['identity','round'],media:[hero,wireframe],downloads:[pngDownload,svgDownload],relatedShowcaseIds:['atlas/scene']},
  {id:'atlas/scene',projectId:'atlas',slug:'scene',title:'Atlas Scene',description:'An exploratory environment and its development view',category:'environment',publication:'showcase',tags:['3D','development'],media:[wireframe],downloads:[],relatedShowcaseIds:['cv/icon']},
  {id:'atlas/missing',projectId:'atlas',slug:'missing',title:'Missing Preview',description:'A fallback view',category:'environment',publication:'showcase',media:[missingPreview],downloads:[]},
]};

const browser = await chromium.launch({headless:true});
try {
  const page = await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
  const errors = [];
  page.on('pageerror',error => errors.push(error.message));
  await page.goto(url,{waitUntil:'networkidle'});
  assert.equal(await page.title(),'Overview — Asset Studio');
  assert.equal(await page.locator('.stat-card').first().locator('strong').innerText(),'0');
  assert.ok((await page.locator('main').innerText()).includes('No showcases have been approved for public display yet.'));
  await page.screenshot({path:join(screenshots,'qa-overview-light.png'),fullPage:true});
  await page.getByRole('button',{name:'Switch to dark mode'}).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.screenshot({path:join(screenshots,'qa-overview-dark.png'),fullPage:true});
  await page.getByRole('link',{name:'Explore',exact:true}).click();
  assert.equal(new URL(page.url()).pathname,'/explore');
  assert.ok(await page.getByRole('heading',{name:'The gallery is taking shape'}).isVisible());
  for (const [path,heading] of [['/collections','Collections'],['/health','Asset Health'],['/about','A home for considered assets']]) {
    await page.goto(new URL(path,url).toString(),{waitUntil:'networkidle'});
    assert.ok(await page.getByRole('heading',{name:heading,exact:true}).isVisible());
  }
  await page.goto(new URL('/assets/cv/icon',url).toString(),{waitUntil:'networkidle'});
  assert.ok(await page.getByRole('heading',{name:'Showcase not found'}).isVisible());
  await page.goto(url,{waitUntil:'networkidle'});
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement?.textContent?.trim()),'Skip to content');
  const mobile = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
  await mobile.goto(url,{waitUntil:'networkidle'});
  await mobile.getByRole('button',{name:'Open navigation'}).click();
  await mobile.keyboard.press('Escape');
  assert.equal(await mobile.getByRole('navigation',{name:'Mobile navigation'}).count(),0);
  await mobile.screenshot({path:join(screenshots,'qa-overview-mobile.png'),fullPage:true});
  const missing = await browser.newPage();
  await missing.route('**/catalog.json',route => route.fulfill({status:404,body:'missing'}));
  await missing.goto(url,{waitUntil:'networkidle'});
  assert.ok(await missing.getByRole('heading',{name:'Catalog unavailable'}).isVisible());
  const malformed = await browser.newPage();
  await malformed.route('**/catalog.json',route => route.fulfill({contentType:'application/json',body:'{}'}));
  await malformed.goto(url,{waitUntil:'networkidle'});
  assert.ok(await malformed.getByRole('heading',{name:'Catalog unavailable'}).isVisible());

  const fixture = await browser.newPage({viewport:{width:1440,height:900}});
  fixture.on('pageerror',error => errors.push(error.message));
  await fixture.route('**/catalog.json',route => route.fulfill({contentType:'application/json',body:JSON.stringify(fixtureCatalog)}));
  await fixture.route('**/published/*',route => {
    const path = new URL(route.request().url()).pathname;
    if (path === missingPreview.url) return route.fulfill({status:404,body:'missing'});
    if (path === wireframe.url) return route.fulfill({contentType:'image/png',body:detailPicture});
    if (path === svgDownload.url) return route.fulfill({contentType:'image/svg+xml',body:svg});
    return route.fulfill({contentType:'image/png',body:picture});
  });
  await fixture.goto(new URL('/explore',url).toString(),{waitUntil:'networkidle'});
  assert.equal(await fixture.locator('.asset-card').count(),3);
  assert.ok(await fixture.getByLabel('Preview unavailable',{exact:true}).isVisible());
  await fixture.screenshot({path:join(screenshots,'qa-showcase-grid.png'),fullPage:true});
  await fixture.getByRole('button',{name:'List view'}).click();
  assert.equal(new URL(fixture.url()).searchParams.get('view'),'list');
  assert.equal(await fixture.locator('.asset-card-list').count(),3);
  await fixture.getByRole('combobox',{name:'Project'}).selectOption('cv');
  await fixture.getByRole('combobox',{name:'Category'}).selectOption('branding');
  await fixture.getByRole('combobox',{name:'Format'}).selectOption('png');
  assert.equal(await fixture.locator('.asset-card').count(),1);
  await fixture.getByRole('button',{name:'Clear filters'}).click();
  assert.equal(await fixture.locator('.asset-card').count(),3);
  const search = fixture.getByRole('searchbox',{name:'Search public showcases'});
  await search.fill('identity');
  assert.equal(await fixture.locator('.asset-card').count(),1);
  assert.equal(await fixture.locator('.asset-card h2').first().innerText(),'CV Icon');
  await search.fill('nothing matches');
  assert.ok(await fixture.getByRole('heading',{name:'No matching assets'}).isVisible());
  await fixture.goBack({waitUntil:'networkidle'});
  assert.equal(await fixture.locator('.asset-card').count(),1);
  await fixture.goto(new URL('/explore',url).toString(),{waitUntil:'networkidle'});
  await fixture.getByRole('link',{name:'View CV Icon'}).click();
  assert.equal(new URL(fixture.url()).pathname,'/assets/cv/icon');
  assert.equal(await fixture.title(),'CV Icon — Asset Studio');
  assert.ok(await fixture.getByText('Final render',{exact:true}).first().isVisible());
  assert.equal(await fixture.locator('.detail-downloads a').count(),2);
  await fixture.getByRole('button',{name:'Show image 2: Wireframe study'}).click();
  assert.equal(await fixture.getByRole('button',{name:'Show image 2: Wireframe study'}).getAttribute('aria-pressed'),'true');
  assert.ok(await fixture.locator('.detail-caption').getByText('Wireframe study').isVisible());
  const mailto = await fixture.getByRole('link',{name:'Request Asset'}).getAttribute('href');
  assert.ok(mailto?.startsWith('mailto:requests@example.test?'));
  assert.ok(decodeURIComponent(mailto).includes('"CV Icon" (cv/icon)'));
  assert.ok(!mailto.includes('projects/'));
  await fixture.evaluate(() => { window.scrollTo(0,0); if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); });
  await fixture.screenshot({path:join(screenshots,'qa-showcase-detail.png'),fullPage:true});
  await fixture.getByRole('link',{name:'Atlas Scene'}).click();
  assert.equal(new URL(fixture.url()).pathname,'/assets/atlas/scene');
  assert.equal(await fixture.locator('.detail-downloads a').count(),0);
  assert.ok(await fixture.getByText('Showcase only',{exact:true}).isVisible());
  await fixture.reload({waitUntil:'networkidle'});
  assert.ok(await fixture.getByRole('heading',{name:'Atlas Scene'}).isVisible());
  await fixture.goto(new URL('/collections',url).toString(),{waitUntil:'networkidle'});
  assert.equal(await fixture.locator('.collection-link').count(),2);
  await fixture.getByRole('link',{name:/CV/}).click();
  assert.equal(new URL(fixture.url()).pathname,'/collections/cv');
  assert.equal(await fixture.locator('.asset-card').count(),1);
  const fixtureMobile = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
  await fixtureMobile.route('**/catalog.json',route => route.fulfill({contentType:'application/json',body:JSON.stringify(fixtureCatalog)}));
  await fixtureMobile.route('**/published/*',route => route.fulfill({contentType:'image/png',body:new URL(route.request().url()).pathname === wireframe.url ? detailPicture : picture}));
  await fixtureMobile.goto(new URL('/assets/cv/icon',url).toString(),{waitUntil:'networkidle'});
  assert.ok(await fixtureMobile.getByRole('heading',{name:'CV Icon'}).isVisible());
  assert.ok(await fixtureMobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await fixtureMobile.screenshot({path:join(screenshots,'qa-showcase-detail-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Website UI verified: empty catalog, themes, keyboard, desktop/mobile, grouped gallery, search/filter/history, detail routes, ordered media, request mailto, download states, related assets, and missing previews.');
  console.log(`Screenshots: ${screenshots}/qa-*.png`);
} finally { await browser.close(); }
